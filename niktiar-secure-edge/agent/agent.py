#!/usr/bin/env python3
"""NikTiar Secure Edge agent — heartbeat, hybrid site-map sync, tenant-isolated events."""
from __future__ import annotations

import json
import os
import re
import subprocess
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

import requests
import yaml

CFG = yaml.safe_load(Path("/app/config.yaml").read_text()) if Path("/app/config.yaml").exists() else {}
CONTROL = (os.getenv("NIKTIAR_CONTROL_URL") or "").rstrip("/")
TOKEN = os.getenv("NIKTIAR_APPLIANCE_TOKEN") or ""
TENANT = (os.getenv("NIKTIAR_TENANT_CODE") or "").strip().upper()
HOST = os.getenv("SECURE_EDGE_HOSTNAME") or "niktiar-secure-edge"
_raw_mode = (os.getenv("SECURE_EDGE_MODE") or "dedicated").lower().strip()
MODE = "dedicated"  # product default — shared multi-tenant offering retired
FORM_FACTOR = (os.getenv("SECURE_EDGE_FORM_FACTOR") or "ha_pair").lower().strip()
if FORM_FACTOR not in ("ha_pair", "physical"):
    FORM_FACTOR = "ha_pair"
# keep _raw_mode available for diagnostics only
_ = _raw_mode
POLL = int(CFG.get("poll_seconds") or 30)
RUNTIME = Path(os.getenv("RUNTIME_DIR") or "/runtime")
CADDY_CFG = Path(os.getenv("CADDY_CONFIG_DIR") or "/config/caddy")
WAF_CONTAINER = os.getenv("WAF_CONTAINER") or "niktiar-se-waf"
ACCESS_LOG = Path(os.getenv("ACCESS_LOG") or "/runtime/niktiar-access.log")
TENANT_MAP_PATH = RUNTIME / "tenant_map.json"
VERSION = "0.4.0-ngfw"
_last_config_version = -1
_log_offset = 0


def headers() -> Dict[str, str]:
    h = {"Content-Type": "application/json", "User-Agent": f"NikTiar-SecureEdge/{VERSION}"}
    if TOKEN:
        h["Authorization"] = f"Bearer {TOKEN}"
    return h


def _safe_name(value: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_]", "_", value)[:48]


def _norm_host(h: Optional[str]) -> str:
    return (h or "").strip().lower().split(":")[0]


def load_tenant_map() -> Dict[str, str]:
    if TENANT_MAP_PATH.exists():
        try:
            raw = json.loads(TENANT_MAP_PATH.read_text(encoding="utf-8"))
            return {_norm_host(k): str(v).upper() for k, v in (raw or {}).items()}
        except Exception:  # noqa: BLE001
            pass
    # fallback from sites.json
    sites_path = RUNTIME / "sites.json"
    out: Dict[str, str] = {}
    if sites_path.exists():
        try:
            data = json.loads(sites_path.read_text(encoding="utf-8"))
            for s in data.get("sites") or []:
                host = _norm_host(s.get("public_hostname"))
                t = (s.get("tenant_short_code") or "").strip().upper()
                if host and t:
                    out[host] = t
        except Exception:  # noqa: BLE001
            pass
    return out


def save_tenant_map_from_sites(sites: List[Dict[str, Any]]) -> Dict[str, str]:
    out: Dict[str, str] = {}
    for s in sites:
        host = _norm_host(s.get("public_hostname"))
        t = (s.get("tenant_short_code") or "").strip().upper() or "UNKNOWN"
        if host:
            out[host] = t
    RUNTIME.mkdir(parents=True, exist_ok=True)
    TENANT_MAP_PATH.write_text(json.dumps(out, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return out


def render_sites_caddy(sites: List[Dict[str, Any]]) -> str:
    """Host-exact reverse_proxy only — unknown hosts denied by base Caddyfile."""
    lines = [
        "# Auto-generated by NikTiar Secure Edge agent — tenant isolation",
        f"# mode={MODE} host={HOST} sites={len(sites)}",
    ]
    for site in sites:
        public_host = _norm_host(site.get("public_hostname"))
        origin = (site.get("origin_url") or "").strip()
        tenant = (site.get("tenant_short_code") or "").strip().upper() or "UNKNOWN"
        if MODE == "dedicated" and TENANT and tenant != TENANT:
            lines.append(f"# skipped cross-tenant {public_host} tenant={tenant} pin={TENANT}")
            continue
        if not public_host or not origin:
            continue
        matcher = f"site_{_safe_name(public_host)}"
        lines.append(f"@{matcher} host {public_host}")
        lines.append(f"handle @{matcher} {{")
        lines.append(f'\theader X-NikTiar-Tenant-Code "{tenant}"')
        lines.append(f'\theader X-NikTiar-Zone "{public_host}"')
        lines.append(f"\treverse_proxy {origin} {{")
        lines.append("\t\ttrusted_proxies private_ranges")
        lines.append("\t\theader_up X-NikTiar-Tenant {http.request.host}")
        lines.append(f'\t\theader_up X-NikTiar-Tenant-Code "{tenant}"')
        lines.append("\t}")
        lines.append("}")
        lines.append("")
    if len(lines) <= 2:
        lines.append("# (no tenant sites — unknown Host → 421 by Caddyfile)")
    return "\n".join(lines) + "\n"


def render_sites_tls_caddy(sites: List[Dict[str, Any]]) -> str:
    lines = [
        "# Auto-generated TLS/ACME site blocks — tenant isolation",
        f"# mode={MODE} host={HOST}",
    ]
    any_tls = False
    for site in sites:
        if (site.get("tls_mode") or "").lower() != "acme":
            continue
        public_host = _norm_host(site.get("public_hostname"))
        origin = (site.get("origin_url") or "").strip()
        tenant = (site.get("tenant_short_code") or "").strip().upper() or "UNKNOWN"
        if MODE == "dedicated" and TENANT and tenant != TENANT:
            continue
        if not public_host or not origin:
            continue
        any_tls = True
        lines.append(f"{public_host} {{")
        lines.append("\ttls")
        lines.append("\timport coraza_block")
        lines.append(f'\theader X-NikTiar-Tenant-Code "{tenant}"')
        lines.append(f"\treverse_proxy {origin} {{")
        lines.append("\t\ttrusted_proxies private_ranges")
        lines.append(f'\t\theader_up X-NikTiar-Tenant-Code "{tenant}"')
        lines.append("\t}")
        lines.append("}")
        lines.append("")
    if not any_tls:
        lines.append("# (no ACME sites)")
    return "\n".join(lines) + "\n"


def reload_caddy() -> bool:
    try:
        sites_path = RUNTIME / "sites.caddy"
        if not sites_path.exists():
            sites_path.write_text("# empty\n", encoding="utf-8")
        prep = [
            "docker",
            "exec",
            WAF_CONTAINER,
            "sh",
            "-c",
            "cp /config/caddy/Caddyfile /etc/caddy/Caddyfile && "
            "caddy reload --config /etc/caddy/Caddyfile --force",
        ]
        r = subprocess.run(prep, capture_output=True, text=True, timeout=30)
        if r.returncode != 0:
            print(f"caddy reload failed: {r.stderr or r.stdout}", flush=True)
            return False
        print("caddy reload ok", flush=True)
        return True
    except Exception as exc:  # noqa: BLE001
        print(f"caddy reload error: {exc}", flush=True)
        return False


def heartbeat() -> None:
    if not CONTROL:
        print("heartbeat skip: NIKTIAR_CONTROL_URL unset", flush=True)
        return
    url = CONTROL + (CFG.get("heartbeat_path") or "/api/v1/secure-edge/heartbeat")
    body = {
        "hostname": HOST,
        "tenant_short_code": TENANT or None,
        "status": "online",
        "version": VERSION,
        "deployment_mode": MODE,
        "capabilities": [
            "waf_coraza_crs",
            "caddy",
            "crowdsec",
            "hybrid_multitenant",
            "strong_tenant_isolation",
            "unknown_host_deny",
            "host_scoped_firewall",
            "site_map_sync",
            "ngfw_policies",
            "url_filtering",
            "rate_limiting_enforced",
            "zone_settings_sync",
        ],
    }
    try:
        r = requests.post(url, headers=headers(), json=body, timeout=15)
        print(f"heartbeat {r.status_code}", flush=True)
    except Exception as exc:  # noqa: BLE001
        print(f"heartbeat error: {exc}", flush=True)


def sync_config() -> None:
    global _last_config_version
    if not CONTROL:
        return
    url = CONTROL + (CFG.get("config_path") or "/api/v1/secure-edge/config")
    try:
        r = requests.get(
            url,
            headers=headers(),
            params={"hostname": HOST, "mode": MODE},
            timeout=20,
        )
        if r.status_code != 200:
            print(f"config pull {r.status_code}", flush=True)
            return
        data = r.json()
        version = int(data.get("config_version") or 0)
        sites = data.get("sites") or []
        if MODE == "dedicated" and TENANT:
            sites = [
                s
                for s in sites
                if (s.get("tenant_short_code") or "").strip().upper() == TENANT
            ]
        if version == _last_config_version:
            return
        RUNTIME.mkdir(parents=True, exist_ok=True)
        (RUNTIME / "sites.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
        save_tenant_map_from_sites(sites)

        edge_cfg_path = RUNTIME / "edge_config.json"
        if edge_cfg_path.exists():
            try:
                cfg = json.loads(edge_cfg_path.read_text(encoding="utf-8"))
            except Exception:  # noqa: BLE001
                cfg = {"version": 3, "global": {}, "zones": [], "custom_waf_rules": []}
            by_host = {
                _norm_host(z.get("public_hostname")): z for z in (cfg.get("zones") or [])
            }
            for s in sites:
                host = _norm_host(s.get("public_hostname"))
                if not host:
                    continue
                tcode = (s.get("tenant_short_code") or "").strip().upper() or "LOCAL"
                z = by_host.get(host) or {
                    "id": host,
                    "public_hostname": host,
                    "ssl_mode": "flexible",
                    "waf": {
                        "managed_ruleset": "owasp_crs",
                        "mode": "block",
                        "paranoia_level": 1,
                        "anomaly_inbound": 5,
                        "anomaly_outbound": 4,
                    },
                    "firewall": {"ip_allow": [], "ip_block": [], "ua_block": [], "asn_block": []},
                    "rate_limit_rules": [],
                    "cache": {"enabled": False, "mode": "bypass", "edge_ttl_seconds": 3600},
                    "under_attack_mode": False,
                    "enabled": True,
                }
                z["public_hostname"] = host
                z["origin_url"] = s.get("origin_url") or z.get("origin_url")
                z["tenant_short_code"] = tcode
                z["enabled"] = bool(s.get("enabled", True))
                # Merge control-plane zone_settings (WAF / firewall / rate_limit / cache / SSL)
                zs = s.get("zone_settings") if isinstance(s.get("zone_settings"), dict) else {}
                if zs:
                    if isinstance(zs.get("waf"), dict):
                        z["waf"] = {**(z.get("waf") or {}), **zs["waf"]}
                    if isinstance(zs.get("firewall"), dict):
                        z["firewall"] = {**(z.get("firewall") or {}), **zs["firewall"]}
                    if isinstance(zs.get("rate_limit_rules"), list):
                        z["rate_limit_rules"] = zs["rate_limit_rules"]
                    if isinstance(zs.get("cache"), dict):
                        z["cache"] = {**(z.get("cache") or {}), **zs["cache"]}
                    if zs.get("ssl_mode"):
                        z["ssl_mode"] = zs["ssl_mode"]
                    if zs.get("security_level"):
                        z["security_level"] = zs["security_level"]
                    if "under_attack_mode" in zs:
                        z["under_attack_mode"] = bool(zs.get("under_attack_mode"))
                    if isinstance(zs.get("ngfw_policies"), list):
                        z["ngfw_policies"] = zs["ngfw_policies"]
                by_host[host] = z
            # dedicated: drop foreign zones
            zones = list(by_host.values())
            if MODE == "dedicated" and TENANT:
                zones = [
                    z
                    for z in zones
                    if (z.get("tenant_short_code") or "").strip().upper() == TENANT
                ]
            cfg["zones"] = zones
            edge_cfg_path.write_text(json.dumps(cfg, indent=2), encoding="utf-8")
            (RUNTIME / "sites.caddy").write_text(render_sites_caddy(sites), encoding="utf-8")
            (RUNTIME / "sites_tls.caddy").write_text(render_sites_tls_caddy(sites), encoding="utf-8")
        else:
            (RUNTIME / "sites.caddy").write_text(render_sites_caddy(sites), encoding="utf-8")
            (RUNTIME / "sites_tls.caddy").write_text(render_sites_tls_caddy(sites), encoding="utf-8")

        if reload_caddy():
            _last_config_version = version
            print(f"config applied version={version} sites={len(sites)} isolation=on", flush=True)
    except Exception as exc:  # noqa: BLE001
        print(f"config sync error: {exc}", flush=True)


def ship_events(events: List[Dict[str, Any]]) -> None:
    if not CONTROL or not events:
        return
    url = CONTROL + (CFG.get("events_path") or "/api/v1/secure-edge/events")
    try:
        r = requests.post(
            url,
            headers=headers(),
            json={"edge_hostname": HOST, "events": events},
            timeout=15,
        )
        print(f"events ship {r.status_code} n={len(events)}", flush=True)
    except Exception as exc:  # noqa: BLE001
        print(f"events ship error: {exc}", flush=True)


def tail_access_blocks() -> None:
    global _log_offset
    try:
        if not ACCESS_LOG.is_file() or ACCESS_LOG.is_symlink():
            return
        r = subprocess.run(
            ["tail", "-n", "120", str(ACCESS_LOG)],
            capture_output=True,
            text=True,
            timeout=3,
        )
        chunk = r.stdout or ""
        marker = len(chunk)
        if marker == _log_offset and marker > 0:
            return
        _log_offset = marker
        tmap = load_tenant_map()
        events: List[Dict[str, Any]] = []
        seen = set()
        for line in chunk.splitlines():
            status = None
            host = None
            try:
                obj = json.loads(line)
                status = int(obj.get("status") or 0)
                req = obj.get("request") or {}
                host = req.get("host")
                if not host:
                    hdrs = req.get("headers") or {}
                    hv = hdrs.get("Host") or hdrs.get("host")
                    host = hv[0] if isinstance(hv, list) and hv else hv
            except Exception:  # noqa: BLE001
                if "403" in line or "421" in line:
                    status = 403 if "403" in line else 421
            host_n = _norm_host(host)
            tenant = tmap.get(host_n) if host_n else None
            if MODE == "dedicated" and TENANT:
                if tenant and tenant != TENANT:
                    continue  # never ship other-tenant noise
                tenant = tenant or TENANT
            if status in (403, 421, 429, 503) or (isinstance(status, int) and status >= 500):
                key = f"{status}:{host_n}:{line[-80:]}"
                if key in seen:
                    continue
                seen.add(key)
                events.append(
                    {
                        "tenant_short_code": tenant,
                        "public_hostname": host_n or None,
                        "event_type": (
                            "unknown_host_denied"
                            if status == 421
                            else ("waf_block" if status == 403 else "http_error")
                        ),
                        "severity": "high" if status in (403, 421) else "medium",
                        "summary": f"HTTP {status} on {host_n or HOST}",
                        "details": {
                            "status": status,
                            "tenant_short_code": tenant,
                            "public_hostname": host_n,
                            # do not ship raw log lines that may contain other hosts' URIs mixed — truncate
                            "raw_excerpt": line[:300],
                        },
                    }
                )
        ship_events(events[:50])
    except Exception as exc:  # noqa: BLE001
        print(f"log tail error: {exc}", flush=True)


def main() -> None:
    print(
        f"NikTiar Secure Edge agent v{VERSION} host={HOST} mode={MODE} "
        f"pin={TENANT or '-'} control={CONTROL or 'NONE'}",
        flush=True,
    )
    RUNTIME.mkdir(parents=True, exist_ok=True)
    if not (RUNTIME / "sites.caddy").exists():
        (RUNTIME / "sites.caddy").write_text("# bootstrap\n", encoding="utf-8")
    while True:
        heartbeat()
        sync_config()
        tail_access_blocks()
        time.sleep(POLL)


if __name__ == "__main__":
    main()
