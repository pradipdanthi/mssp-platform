"""Cloudflare-parity Secure Edge config model + Coraza/Caddy apply engine."""
from __future__ import annotations

import json
import re
import secrets
import subprocess
from copy import deepcopy
from pathlib import Path
from typing import Any, Dict, List, Optional

RUNTIME = Path("/runtime")
CONFIG_PATH = RUNTIME / "edge_config.json"
OVERRIDES = RUNTIME / "coraza-overrides"
RULES_D = RUNTIME / "coraza-rules.d"
SITES_CADDY = RUNTIME / "sites.caddy"
SITES_TLS = RUNTIME / "sites_tls.caddy"
FIREWALL_CADDY = RUNTIME / "firewall.caddy"
WAF_CONTAINER = "niktiar-se-waf"

SECURITY_LEVELS = ("off", "essentially_off", "low", "medium", "high", "under_attack")

DEFAULT_GLOBAL = {
    "security_level": "medium",
    "waf_enabled": True,
    "bot_fight_mode": True,
    "browser_integrity_check": True,
    "always_use_https": False,
    "challenge_passage_seconds": 1800,
    "managed_ruleset": "owasp_crs",
}

DEFAULT_ZONE_WAF = {
    "managed_ruleset": "owasp_crs",
    "mode": "block",  # block | simulate
    "paranoia_level": 1,
    "anomaly_inbound": 5,
    "anomaly_outbound": 4,
}

DEFAULT_ZONE = {
    "ssl_mode": "flexible",  # off | flexible | full | strict  (CF mental model)
    "security_level": None,  # inherit global
    "waf": deepcopy(DEFAULT_ZONE_WAF),
    "firewall": {
        "ip_allow": [],
        "ip_block": [],
        "ua_block": [],
        "asn_block": [],
    },
    "rate_limit_rules": [],
    "cache": {"enabled": False, "mode": "bypass", "edge_ttl_seconds": 3600},
    "page_rules": [],
    "under_attack_mode": False,
}


def default_config() -> Dict[str, Any]:
    return {
        "version": 2,
        "global": deepcopy(DEFAULT_GLOBAL),
        "zones": [],
        "custom_waf_rules": [],
    }


def load_config() -> Dict[str, Any]:
    if not CONFIG_PATH.exists():
        cfg = default_config()
        save_config(cfg)
        return cfg
    try:
        data = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        data = default_config()
    data.setdefault("version", 2)
    data.setdefault("global", deepcopy(DEFAULT_GLOBAL))
    data.setdefault("zones", [])
    data.setdefault("custom_waf_rules", [])
    return data


def save_config(cfg: Dict[str, Any]) -> None:
    RUNTIME.mkdir(parents=True, exist_ok=True)
    CONFIG_PATH.write_text(json.dumps(cfg, indent=2), encoding="utf-8")


def _safe(s: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_]", "_", s)[:48]


def _level_to_coraza(level: str, waf: Dict[str, Any]) -> Dict[str, Any]:
    """Map Cloudflare security level → CRS paranoia / anomaly / engine."""
    level = (level or "medium").lower()
    mode = (waf.get("mode") or "block").lower()
    if level == "off":
        return {"engine": "Off", "paranoia": 1, "inbound": 1000, "outbound": 1000}
    if level == "essentially_off":
        return {"engine": "DetectionOnly", "paranoia": 1, "inbound": 1000, "outbound": 1000}
    if level == "low":
        return {
            "engine": "DetectionOnly" if mode == "simulate" else "On",
            "paranoia": 1,
            "inbound": 10,
            "outbound": 8,
        }
    if level == "high":
        return {
            "engine": "DetectionOnly" if mode == "simulate" else "On",
            "paranoia": 2,
            "inbound": int(waf.get("anomaly_inbound") or 5),
            "outbound": int(waf.get("anomaly_outbound") or 4),
        }
    if level == "under_attack":
        return {
            "engine": "On",
            "paranoia": 3,
            "inbound": 3,
            "outbound": 3,
        }
    # medium (default)
    return {
        "engine": "DetectionOnly" if mode == "simulate" else "On",
        "paranoia": int(waf.get("paranoia_level") or 1),
        "inbound": int(waf.get("anomaly_inbound") or 5),
        "outbound": int(waf.get("anomaly_outbound") or 4),
    }


def _write_coraza_overrides(cfg: Dict[str, Any]) -> None:
    OVERRIDES.mkdir(parents=True, exist_ok=True)
    RULES_D.mkdir(parents=True, exist_ok=True)
    g = cfg.get("global") or {}
    # Pick strictest zone level for global CRS knobs (appliance-wide engine)
    level = g.get("security_level") or "medium"
    waf = deepcopy(DEFAULT_ZONE_WAF)
    for z in cfg.get("zones") or []:
        zl = z.get("security_level") or level
        if SECURITY_LEVELS.index(zl) if zl in SECURITY_LEVELS else 0 > (
            SECURITY_LEVELS.index(level) if level in SECURITY_LEVELS else 0
        ):
            level = zl
        if z.get("waf"):
            waf.update(z["waf"])
        if z.get("under_attack_mode"):
            level = "under_attack"
    if not g.get("waf_enabled", True):
        level = "off"
    params = _level_to_coraza(level, waf)
    (OVERRIDES / "10900-niktiar-security-level.conf").write_text(
        f"""# Generated by NikTiar Secure Edge — security_level={level}
# Use 1090xxx IDs so we never collide with CRS 900000–901xxx
SecRuleEngine {params['engine']}
SecAction "id:1090000,phase:1,nolog,pass,t:none,setvar:tx.blocking_paranoia_level={params['paranoia']}"
SecAction "id:1090001,phase:1,nolog,pass,t:none,setvar:tx.detection_paranoia_level={params['paranoia']}"
SecAction "id:1090010,phase:1,nolog,pass,t:none,setvar:tx.inbound_anomaly_score_threshold={params['inbound']}"
SecAction "id:1090011,phase:1,nolog,pass,t:none,setvar:tx.outbound_anomaly_score_threshold={params['outbound']}"
""",
        encoding="utf-8",
    )
    stale_ov = OVERRIDES / "90000-niktiar-security-level.conf"
    if stale_ov.exists():
        stale_ov.unlink()

    # Bot Fight Mode — high ID band avoids CRS collisions (1_100_000+)
    bot_lines = ["# Generated bot/BIC rules"]
    if g.get("bot_fight_mode", True):
        bot_lines.append(
            'SecRule REQUEST_HEADERS:User-Agent "@rx (?i)(semrush|ahrefs|mj12bot|masscan|nikto|sqlmap|zgrab)" '
            '"id:1100100,phase:1,deny,status:403,log,msg:\'NikTiar Bot Fight blocked scanner UA\'"'
        )
        bot_lines.append(
            'SecRule REQUEST_HEADERS:User-Agent "@rx ^$" '
            '"id:1100101,phase:1,deny,status:403,log,msg:\'NikTiar Bot Fight empty UA\'"'
        )
    if g.get("browser_integrity_check", True):
        bot_lines.append(
            'SecRule REQUEST_HEADERS:Accept "@rx ^$" '
            '"id:1100110,phase:1,pass,nolog,msg:\'NikTiar BIC missing Accept\'"'
        )
    (RULES_D / "11000-bot-fight.conf").write_text("\n".join(bot_lines) + "\n", encoding="utf-8")
    # remove old colliding file if present
    old = RULES_D / "90100-bot-fight.conf"
    if old.exists():
        old.unlink()

    # Custom WAF rules (Cloudflare Custom Rules analogue)
    custom_lines = ["# Generated custom WAF rules"]
    rid = 1101000
    for rule in cfg.get("custom_waf_rules") or []:
        if not rule.get("enabled", True):
            continue
        action = (rule.get("action") or "block").lower()
        expr = (rule.get("expression") or "").strip()
        if not expr:
            continue
        # Very small expression language: field op value
        # Examples: path contains /admin | ip eq 1.2.3.4 | ua contains curl | uri_query contains union
        sec = _expr_to_secrule(expr, rid, action, rule.get("name") or "custom")
        if sec:
            custom_lines.append(sec)
            rid += 1
    (RULES_D / "11010-custom-rules.conf").write_text("\n".join(custom_lines) + "\n", encoding="utf-8")
    for stale in ("91000-custom-rules.conf",):
        p = RULES_D / stale
        if p.exists():
            p.unlink()

    # IP block/allow → Coraza
    ip_lines = ["# Generated IP access rules"]
    rid = 1102000
    for z in cfg.get("zones") or []:
        fw = z.get("firewall") or {}
        for ip in fw.get("ip_block") or []:
            ip = str(ip).strip()
            if not ip:
                continue
            ip_lines.append(
                f'SecRule REMOTE_ADDR "@ipMatch {ip}" "id:{rid},phase:1,deny,status:403,log,'
                f'msg:\'NikTiar IP block {ip}\'"'
            )
            rid += 1
        for ip in fw.get("ip_allow") or []:
            ip = str(ip).strip()
            if not ip:
                continue
            ip_lines.append(
                f'SecRule REMOTE_ADDR "@ipMatch {ip}" "id:{rid},phase:1,allow,nolog,'
                f'msg:\'NikTiar IP allow {ip}\'"'
            )
            rid += 1
        for ua in fw.get("ua_block") or []:
            ua = str(ua).strip()
            if not ua:
                continue
            esc = ua.replace("\\", "\\\\").replace('"', '\\"')
            ip_lines.append(
                f'SecRule REQUEST_HEADERS:User-Agent "@contains {esc}" "id:{rid},phase:1,deny,status:403,log,'
                f'msg:\'NikTiar UA block\'"'
            )
            rid += 1
    (RULES_D / "11020-ip-access.conf").write_text("\n".join(ip_lines) + "\n", encoding="utf-8")
    for stale in ("92000-ip-access.conf",):
        p = RULES_D / stale
        if p.exists():
            p.unlink()


def _expr_to_secrule(expr: str, rid: int, action: str, name: str) -> Optional[str]:
    """Minimal CF-like expression → SecRule."""
    expr_l = expr.lower().strip()
    var = "REQUEST_URI"
    op = "@contains"
    value = expr
    m = re.match(
        r"^(path|uri|url|ip|ua|user_agent|query|uri_query)\s+"
        r"(eq|equals|contains|matches)\s+(.+)$",
        expr.strip(),
        re.I,
    )
    if m:
        field, oper, value = m.group(1).lower(), m.group(2).lower(), m.group(3).strip().strip("\"'")
        if field in ("path", "uri", "url"):
            var = "REQUEST_URI"
        elif field == "ip":
            var = "REMOTE_ADDR"
        elif field in ("ua", "user_agent"):
            var = "REQUEST_HEADERS:User-Agent"
        elif field in ("query", "uri_query"):
            var = "ARGS_COMBINED_SIZE" if False else "REQUEST_URI"  # use QUERY_STRING
            var = "QUERY_STRING"
        if oper in ("eq", "equals"):
            op = f"@streq {value}"
        elif oper == "matches":
            op = f"@rx {value}"
        else:
            op = f"@contains {value}"
    else:
        # bare substring against URI
        op = f"@contains {expr.strip().strip(chr(34))}"
        var = "REQUEST_URI"

    act = "deny,status:403"
    if action in ("log",):
        act = "pass,log"
    elif action == "allow":
        act = "allow"
    elif action in ("challenge", "js_challenge"):
        act = "deny,status:503"  # challenge page via Caddy for UAM; here hard deny fallback
    msg = name.replace("'", "")
    if op.startswith("@streq ") or op.startswith("@rx ") or op.startswith("@contains "):
        return f'SecRule {var} "{op}" "id:{rid},phase:1,{act},log,msg:\'NikTiar custom: {msg}\'"'
    return None


def _write_caddy_sites(cfg: Dict[str, Any]) -> None:
    g = cfg.get("global") or {}
    lines = ["# Generated sites — Cloudflare-parity zones", f"# security_level={g.get('security_level')}"]
    tls_lines = ["# Generated TLS / ACME zones"]
    fw_lines = ["# Generated firewall / UAM / cache snippets"]

    # Global IP blocks at edge (Caddy) for speed
    all_blocks: List[str] = []
    all_allows: List[str] = []
    for z in cfg.get("zones") or []:
        fw = z.get("firewall") or {}
        all_blocks.extend(fw.get("ip_block") or [])
        all_allows.extend(fw.get("ip_allow") or [])
    if all_blocks:
        ips = " ".join(sorted(set(str(x).strip() for x in all_blocks if str(x).strip())))
        fw_lines.append(f"@edge_block remote_ip {ips}")
        fw_lines.append("handle @edge_block {")
        fw_lines.append('\trespond "Forbidden by NikTiar Secure Edge firewall" 403')
        fw_lines.append("}")

    uam_hosts = []
    if g.get("security_level") == "under_attack":
        uam_hosts = [
            (z.get("public_hostname") or "").strip().lower()
            for z in (cfg.get("zones") or [])
            if z.get("public_hostname")
        ]
    else:
        uam_hosts = [
            (z.get("public_hostname") or "").strip().lower()
            for z in (cfg.get("zones") or [])
            if z.get("under_attack_mode") or z.get("security_level") == "under_attack"
        ]
    uam_hosts = [h for h in uam_hosts if h]
    fw_lines.append("handle /cdn-cgi/challenge-platform/pass {")
    fw_lines.append('\theader Set-Cookie "niktiar_uam=1; Path=/; Max-Age=1800; HttpOnly; SameSite=Lax"')
    fw_lines.append('\theader Content-Type text/html')
    fw_lines.append(
        '\trespond `<html><body style="font-family:system-ui;background:#0b1220;color:#fff;'
        'text-align:center;padding:4rem"><h2>Verified</h2><p><a style="color:#3d9cf0" href="/">Continue to site</a></p>'
        "<script>location.href='/'</script></body></html>` 200"
    )
    fw_lines.append("}")
    if uam_hosts:
        hosts_list = " ".join(uam_hosts)
        fw_lines.append(f"@uam_need {{")
        fw_lines.append(f"\thost {hosts_list}")
        fw_lines.append("\tnot header Cookie *niktiar_uam=1*")
        fw_lines.append("\tnot path /cdn-cgi/*")
        fw_lines.append("\tnot path /healthz")
        fw_lines.append("}")
        fw_lines.append("handle @uam_need {")
        fw_lines.append("\theader Content-Type text/html")
        fw_lines.append(
            '\trespond `<!doctype html><html><head><title>Just a moment...</title></head>'
            "<body style='font-family:system-ui;background:#0b1220;color:#e8eef7;display:flex;"
            "align-items:center;justify-content:center;height:100vh;margin:0'>"
            "<div style='text-align:center;max-width:28rem'>"
            "<h1>NikTiar Secure Edge</h1>"
            "<p>Checking your browser before accessing this website.<br/>Under Attack Mode is enabled.</p>"
            "<p><a style='color:#3d9cf0' href='/cdn-cgi/challenge-platform/pass'>Continue</a></p>"
            "</div>"
            "<script>setTimeout(()=>location.href='/cdn-cgi/challenge-platform/pass',900)</script>"
            "</body></html>` 503"
        )
        fw_lines.append("}")

    FIREWALL_CADDY.write_text("\n".join(fw_lines) + "\n", encoding="utf-8")

    for z in cfg.get("zones") or []:
        if z.get("enabled") is False:
            continue
        host = (z.get("public_hostname") or "").strip().lower()
        origin = (z.get("origin_url") or "").strip()
        if not host or not origin:
            continue
        matcher = f"zone_{_safe(host)}"
        ssl = (z.get("ssl_mode") or "flexible").lower()
        cache = z.get("cache") or {}
        lines.append(f"@{matcher} host {host}")
        lines.append(f"handle @{matcher} {{")
        # Rate limit markers as headers for analytics; real limit via Coraza custom if configured
        for rl in z.get("rate_limit_rules") or []:
            path = rl.get("path") or "/*"
            reqs = int(rl.get("requests") or 100)
            period = int(rl.get("period") or 60)
            lines.append(f"\t# rate_limit {path} {reqs}/{period}s action={rl.get('action','block')}")
        if cache.get("enabled") and cache.get("mode") == "standard":
            ttl = int(cache.get("edge_ttl_seconds") or 3600)
            lines.append(f"\theader Cache-Control \"public, max-age={ttl}\"")
        else:
            lines.append('\theader Cache-Control "no-store"')
        lines.append(f"\treverse_proxy {origin} {{")
        lines.append("\t\ttrusted_proxies private_ranges")
        lines.append("\t\theader_up X-NikTiar-Tenant {http.request.host}")
        lines.append("\t}")
        lines.append("}")
        lines.append("")

        if ssl in ("full", "strict") or (z.get("tls_mode") == "acme"):
            tls_lines.append(f"{host} {{")
            tls_lines.append("\ttls")
            tls_lines.append("\timport coraza_block")
            tls_lines.append("\timport security_headers")
            tls_lines.append(f"\treverse_proxy {origin} {{")
            tls_lines.append("\t\ttrusted_proxies private_ranges")
            tls_lines.append("\t}")
            tls_lines.append("}")
            tls_lines.append("")

    if len(lines) <= 2:
        lines.append("# (no zones)")
    if len(tls_lines) <= 1:
        tls_lines.append("# (no ACME zones)")
    SITES_CADDY.write_text("\n".join(lines) + "\n", encoding="utf-8")
    SITES_TLS.write_text("\n".join(tls_lines) + "\n", encoding="utf-8")

    # Rate-limit as Coraza DOS-ish rules per path
    rl_lines = ["# Generated rate limit approximations"]
    rid = 1103000
    for z in cfg.get("zones") or []:
        for rl in z.get("rate_limit_rules") or []:
            if not rl.get("enabled", True):
                continue
            path = (rl.get("path") or "/").replace("*", ".*")
            reqs = int(rl.get("requests") or 100)
            # CRS-style: deny bursty identical URI from same IP using setvar counter (simplified)
            rl_lines.append(
                f'SecRule REQUEST_URI "@rx ^{path}$" "id:{rid},phase:1,pass,nolog,'
                f'setvar:ip.rl_{rid}=+1,expirevar:ip.rl_{rid}={int(rl.get("period") or 60)}"'
            )
            rid += 1
            rl_lines.append(
                f'SecRule IP:rl_{rid-1} "@gt {reqs}" "id:{rid},phase:1,deny,status:429,log,'
                f'msg:\'NikTiar rate limit exceeded\'"'
            )
            rid += 1
    (RULES_D / "11030-rate-limit.conf").write_text("\n".join(rl_lines) + "\n", encoding="utf-8")
    for stale in ("93000-rate-limit.conf",):
        p = RULES_D / stale
        if p.exists():
            p.unlink()


def reload_caddy(container: str = WAF_CONTAINER) -> Dict[str, Any]:
    try:
        r = subprocess.run(
            [
                "docker",
                "exec",
                container,
                "sh",
                "-c",
                "cp /config/caddy/Caddyfile /etc/caddy/Caddyfile && "
                "caddy reload --config /etc/caddy/Caddyfile --force",
            ],
            capture_output=True,
            text=True,
            timeout=45,
        )
        return {"ok": r.returncode == 0, "stderr": (r.stderr or "")[-500:], "stdout": (r.stdout or "")[-200:]}
    except Exception as exc:  # noqa: BLE001
        return {"ok": False, "error": str(exc)}


def apply_all(cfg: Optional[Dict[str, Any]] = None, container: str = WAF_CONTAINER) -> Dict[str, Any]:
    cfg = cfg or load_config()
    save_config(cfg)
    _write_coraza_overrides(cfg)
    _write_caddy_sites(cfg)
    # Coraza rules.d/overrides are read at process start — need container recreate for CRS vars
    # Caddy reload picks up sites/firewall; for SecRuleEngine changes restart waf
    reload = reload_caddy(container)
    restart = False
    try:
        subprocess.run(["docker", "restart", container], capture_output=True, text=True, timeout=60)
        restart = True
    except Exception:  # noqa: BLE001
        pass
    return {"ok": True, "reload": reload, "waf_restarted": restart, "zones": len(cfg.get("zones") or [])}


def upsert_zone(zone: Dict[str, Any]) -> Dict[str, Any]:
    cfg = load_config()
    host = (zone.get("public_hostname") or "").strip().lower()
    if not host:
        raise ValueError("public_hostname required")
    zones = cfg.get("zones") or []
    found = False
    for i, z in enumerate(zones):
        if (z.get("public_hostname") or "").lower() == host:
            merged = deepcopy(DEFAULT_ZONE)
            merged.update(z)
            merged.update(zone)
            merged["public_hostname"] = host
            if not merged.get("id"):
                merged["id"] = z.get("id") or secrets.token_hex(8)
            zones[i] = merged
            found = True
            break
    if not found:
        merged = deepcopy(DEFAULT_ZONE)
        merged.update(zone)
        merged["public_hostname"] = host
        merged["id"] = zone.get("id") or secrets.token_hex(8)
        zones.append(merged)
    cfg["zones"] = zones
    return apply_all(cfg)


def delete_zone(hostname: str) -> Dict[str, Any]:
    cfg = load_config()
    hostname = hostname.lower().strip()
    cfg["zones"] = [z for z in (cfg.get("zones") or []) if (z.get("public_hostname") or "").lower() != hostname]
    return apply_all(cfg)


def new_id() -> str:
    return secrets.token_hex(8)
