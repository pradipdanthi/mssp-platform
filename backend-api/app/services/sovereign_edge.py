"""NikTiar Sovereign Edge — air-gapped on-prem SOC deployment helpers.

Marketing: NikTiar Sovereign Edge — The Air-Gapped SOC.

Extends the VM199 appliance lineage with local full stack, offline licensing,
optional cloud egress toggle, and no cloud fleet visibility by default.
See docs/KB112_SOVEREIGN_EDGE_TEST_PLAN.md.
"""

from __future__ import annotations

from typing import Optional

SOVEREIGN_EDGE_MODE = "sovereign_edge"

# Modes that register agents to a local appliance Manager (includes sovereign).
LOCAL_APPLIANCE_DEPLOYMENT_MODES = frozenset(
    {
        "cloud_appliance",
        "on_prem_appliance",
        "hybrid",
        SOVEREIGN_EDGE_MODE,
    }
)


def normalize_deployment_mode(deployment_mode: Optional[str]) -> str:
    return (deployment_mode or "cloud").strip().lower()


def is_sovereign_edge(deployment_mode: Optional[str]) -> bool:
    return normalize_deployment_mode(deployment_mode) == SOVEREIGN_EDGE_MODE


def uses_local_appliance_stack(deployment_mode: Optional[str]) -> bool:
    return normalize_deployment_mode(deployment_mode) in LOCAL_APPLIANCE_DEPLOYMENT_MODES


def cloud_fleet_visible(deployment_mode: Optional[str]) -> bool:
    """Sovereign tenants are absent from cloud MSSP fleet dashboards."""
    return not is_sovereign_edge(deployment_mode)


def default_cloud_egress_enabled(deployment_mode: Optional[str]) -> bool:
    """Hybrid Edge forwards critical alerts by default; Sovereign does not."""
    mode = normalize_deployment_mode(deployment_mode)
    if mode == SOVEREIGN_EDGE_MODE:
        return False
    return mode in ("on_prem_appliance", "cloud_appliance", "hybrid")


def offline_license_delivery(deployment_mode: Optional[str]) -> bool:
    """License JWS is generated by MSSP and applied onsite — no channel push."""
    return is_sovereign_edge(deployment_mode)


def skips_cloud_control_plane_fulfillment(deployment_mode: Optional[str]) -> bool:
    """TheHive, Shuffle, and cloud adapters are not provisioned in cloud for sovereign."""
    return is_sovereign_edge(deployment_mode)


def sovereign_onboard_next_steps() -> list[str]:
    return [
        "Provision a 2-node Sovereign Edge cluster from the golden appliance image (VM199+).",
        "Generate an offline license JWS in Admin → export for field delivery.",
        "Onsite engineer applies the license on the cluster; customer dashboard users are read/approve only.",
        "Keep MSSP manual inventory of license expiry; appliance will remind the customer locally.",
        "Cloud alert egress stays disabled unless the SOC engineer enables the optional hybrid bridge.",
    ]
